#!/usr/bin/env python3
"""Small, localhost-only guest dashboard for existing LabLine C++ executable.

No dependencies besides Python 3.11+. Runs strictly allowlisted commands and
reads results generated by the real simulator. Not a public web service.
"""
from __future__ import annotations

import csv
import json
import re
import subprocess
import sys
import threading
import uuid
from datetime import datetime, timezone
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "web_demo"
RUNS = WEB / "runs"
BINARY = ROOT / "build" / "labline"
REPORT = ROOT / "evidence" / "REPORT_2026-11-02.md"
FAULTS = {"none", "ack", "crc", "slow", "crash", "timeout"}
LOCK = threading.Lock()
MAX_JSON = 4096


def read_csv(path: Path, limit: int = 150) -> list[dict[str, str]]:
    if not path.is_file():
        return []
    with path.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))[-limit:]


def benchmark_from_report() -> dict:
    """Parse the checked-in measured report instead of fabricating benchmark numbers."""
    if not REPORT.is_file():
        return {"available": False, "source": "evidence/REPORT_2026-11-02.md"}
    rows = []
    for line in REPORT.read_text(encoding="utf-8").splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 8 or not all(re.fullmatch(r"[0-9.]+", c) for c in cells[:3]):
            continue
        try:
            rows.append({"jobs": int(cells[0]), "workers": int(cells[1]),
                         "runs": int(cells[2]), "throughput": float(cells[4]),
                         "p95_ms": float(cells[5]), "ipc_p95_ms": float(cells[7])})
        except (ValueError, IndexError):
            continue
    rows = [r for r in rows if r["jobs"] in (10, 50, 100) and r["workers"] in (1, 4)]
    return {"available": bool(rows), "rows": rows,
            "source": "evidence/REPORT_2026-11-02.md",
            "note": "Previously measured synthetic Linux IPC results; not live dashboard telemetry."}


def run_payload(run_id: str) -> dict:
    # Run IDs are created server-side (or checked against a strict pattern).
    if not re.fullmatch(r"web-[0-9a-f]{12}", run_id):
        raise ValueError("invalid run identifier")
    path = RUNS / run_id
    if not path.is_dir():
        raise FileNotFoundError("run not found")
    summary = read_csv(path / "summary.csv", 1)
    if not summary:
        raise FileNotFoundError("simulation produced no summary.csv")
    audit_path = path / "audit.json"
    audit = json.loads(audit_path.read_text()) if audit_path.is_file() else None
    meta_path = path / "web_meta.json"
    meta = json.loads(meta_path.read_text()) if meta_path.is_file() else {}
    return {"run": summary[0], "jobs": read_csv(path / "jobs.csv", 110),
            "events": read_csv(path / "events.csv", 80), "audit": audit, "meta": meta}


def list_runs() -> list[dict]:
    if not RUNS.exists():
        return []
    folders = sorted((p for p in RUNS.iterdir() if p.is_dir()
                      and re.fullmatch(r"web-[0-9a-f]{12}", p.name)),
                     key=lambda p: p.stat().st_mtime, reverse=True)[:10]
    out = []
    for folder in folders:
        rows = read_csv(folder / "summary.csv", 1)
        if rows:
            out.append({"id": folder.name, "run": rows[0]})
    return out


def execute_simulation(data: dict) -> dict:
    if not isinstance(data, dict):
        raise ValueError("request must be an object")
    try:
        jobs, workers, seed = int(data.get("jobs", 10)), int(data.get("workers", 4)), int(data.get("seed", 42))
    except (TypeError, ValueError, OverflowError):
        raise ValueError("invalid jobs, workers or seed") from None
    fault = data.get("fault", "none")
    if not (jobs in (10, 50, 100) and workers in (1, 4) and 0 <= seed <= 100000 and fault in FAULTS):
        raise ValueError("Select jobs 10/50/100, workers 1/4, seed 0..100000 and a supported fault")
    if not BINARY.is_file():
        raise RuntimeError("build/labline is missing. Run: cmake -S . -B build && cmake --build build --parallel")
    if not LOCK.acquire(blocking=False):
        raise RuntimeError("Another simulation or test run is in progress")
    try:
        run_id = "web-" + uuid.uuid4().hex[:12]
        path = RUNS / run_id
        path.mkdir(parents=True, exist_ok=False)
        cmd = [str(BINARY), "--jobs", str(jobs), "--workers", str(workers),
               "--seed", str(seed), "--fault", fault, "--out", str(path),
               "--run-id", run_id]
        try:
            result = subprocess.run(cmd, cwd=ROOT, text=True, capture_output=True,
                                    timeout=45, check=False)
            rc = result.returncode
            output = (result.stdout + "\n" + result.stderr).strip()[:6000]
        except subprocess.TimeoutExpired:
            rc, output = 124, "Simulation exceeded the 45-second safety timeout"
        # A failing/crashing *simulated device* intentionally returns exit code 2.
        meta = {"id": run_id, "exit_code": rc, "output": output,
                "finished_at": datetime.now(timezone.utc).isoformat(),
                "explanation": "Exit 2 means the simulator reported failed jobs; exit 0 means all jobs DONE."}
        (path / "web_meta.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
        if (path / "events.csv").is_file() and (path / "summary.csv").is_file():
            try:
                check = subprocess.run([sys.executable, str(ROOT / "python" / "audit_check.py"),
                                        str(path / "events.csv"), "--summary", str(path / "summary.csv")],
                                       cwd=ROOT, text=True, capture_output=True, timeout=15)
                if check.stdout.strip():
                    obj = json.loads(check.stdout)
                    obj["checker_exit_code"] = check.returncode
                    (path / "audit.json").write_text(json.dumps(obj, indent=2), encoding="utf-8")
            except (subprocess.TimeoutExpired, ValueError, OSError):
                pass
        payload = run_payload(run_id) if (path / "summary.csv").exists() else {"run": None, "jobs": [], "events": [], "audit": None, "meta": meta}
        return payload
    finally:
        LOCK.release()


def execute_tests() -> dict:
    if not (ROOT / "build" / "CTestTestfile.cmake").is_file():
        raise RuntimeError("CMake test files missing. Build LabLine first")
    if not LOCK.acquire(blocking=False):
        raise RuntimeError("Another simulation or test run is in progress")
    try:
        try:
            result = subprocess.run(["ctest", "--test-dir", str(ROOT / "build"), "--output-on-failure"],
                                    cwd=ROOT, text=True, capture_output=True, timeout=120)
            output = (result.stdout + "\n" + result.stderr)[-12000:]
            match = re.search(r"(\d+)% tests passed, (\d+) tests failed out of (\d+)", output)
            return {"pass": result.returncode == 0, "exit_code": result.returncode,
                    "passed": int(match.group(3)) - int(match.group(2)) if match else None,
                    "total": int(match.group(3)) if match else None,
                    "output": output}
        except subprocess.TimeoutExpired:
            return {"pass": False, "exit_code": 124, "output": "Tests timed out after 120 seconds"}
    finally:
        LOCK.release()


class Handler(BaseHTTPRequestHandler):
    server_version = "LabLineGuest/1.0"
    def log_message(self, fmt, *args):
        # Don't write user JSON or secrets to logs.
        print("[dashboard] " + fmt % args)

    def send_bytes(self, data: bytes, content_type: str, status=200):
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Cache-Control", "no-store")
        self.send_header("X-Content-Type-Options", "nosniff")
        self.send_header("X-Frame-Options", "DENY")
        self.send_header("Content-Security-Policy", "default-src 'self'; style-src 'self'; script-src 'self'; img-src 'self' data:; connect-src 'self'; frame-ancestors 'none'")
        self.end_headers()
        self.wfile.write(data)

    def send_json(self, value, status=200):
        self.send_bytes(json.dumps(value, default=str).encode("utf-8"), "application/json; charset=utf-8", status)

    def do_GET(self):
        route = urlparse(self.path).path
        if route == "/api/health":
            return self.send_json({"online": True, "binary_ready": BINARY.is_file(),
                                   "tests_ready": (ROOT / "build" / "CTestTestfile.cmake").is_file(),
                                   "mode": "local-guest", "repo": "LabLine-Morphle-AIT"})
        if route == "/api/benchmarks":
            return self.send_json(benchmark_from_report())
        if route == "/api/runs":
            return self.send_json({"runs": list_runs()})
        if route.startswith("/api/runs/"):
            try:
                return self.send_json(run_payload(route[len("/api/runs/"):]))
            except (ValueError, FileNotFoundError):
                return self.send_json({"error": "Run not found"}, 404)
        files = {"/": ("index.html", "text/html; charset=utf-8"),
                 "/style.css": ("style.css", "text/css; charset=utf-8"),
                 "/app.js": ("app.js", "application/javascript; charset=utf-8")}
        if route in files:
            filename, typ = files[route]
            return self.send_bytes((WEB / filename).read_bytes(), typ)
        return self.send_json({"error": "Not found"}, 404)

    def do_POST(self):
        # Host and Origin checks are defense-in-depth for the deliberately unauthenticated local tool.
        host = self.headers.get("Host", "").split(":", 1)[0]
        origin = self.headers.get("Origin", "")
        if host not in ("127.0.0.1", "localhost") or (origin and origin not in (f"http://127.0.0.1:{self.server.server_port}", f"http://localhost:{self.server.server_port}")):
            return self.send_json({"error": "Only localhost requests are permitted"}, 403)
        length = self.headers.get("Content-Length", "0")
        if not length.isdigit() or int(length) > MAX_JSON:
            return self.send_json({"error": "Invalid request size"}, 400)
        try:
            data = json.loads(self.rfile.read(int(length)))
        except (ValueError, UnicodeDecodeError):
            return self.send_json({"error": "Invalid JSON"}, 400)
        try:
            route = urlparse(self.path).path
            if route == "/api/run":
                return self.send_json(execute_simulation(data))
            if route == "/api/tests":
                return self.send_json(execute_tests())
            return self.send_json({"error": "Not found"}, 404)
        except (RuntimeError, ValueError) as exc:
            return self.send_json({"error": str(exc)}, 400)
        except Exception as exc:
            print("[dashboard] unexpected exception:", repr(exc), file=sys.stderr)
            return self.send_json({"error": "Internal error. Inspect terminal logs."}, 500)


def main():
    import argparse
    p = argparse.ArgumentParser()
    p.add_argument("--port", type=int, default=8765)
    args = p.parse_args()
    RUNS.mkdir(exist_ok=True, parents=True)
    server = ThreadingHTTPServer(("127.0.0.1", args.port), Handler)
    print(f"LabLine Guest Dashboard: http://localhost:{args.port}", flush=True)
    print("Local-only: do not port-forward or publish this execution endpoint.", flush=True)
    print(f"C++ ready: {BINARY.is_file()} | Benchmark report ready: {REPORT.is_file()}", flush=True)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nStopping dashboard")
    finally:
        server.server_close()

if __name__ == "__main__":
    main()
